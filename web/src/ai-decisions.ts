/// 把 AI 那一份 `decisions` 拆成「决议」与「待办」两半。
///
/// ══ 为什么需要拆 ══
/// 后端的提示词是**一次生成两者**（`media_ai.rs`）：
///   `("decisions", "用中文列出这次活动的**关键决议**与**待办事项**（谁负责、做什么、何时）…")`
/// 而 `minutes` 表里**本来就是分开的两列**（`resolutions` / `todos`）。
/// 于是「决议事项」和「待办事项」两个导入按钮拉的是**同一份**，
/// 结果两栏里都塞着对方的内容，要记录员手工删 ——
/// ★2026-08-17 liaoruili：「同时把待办也导入了；应该把决议和待办分开吧」★
///
/// ══ ★为什么在前端切，而不是改提示词★ ══
/// 改成两份提示词（`decisions` 只要决议、新增 `todos` 只要待办）**才是真正的修法**，
/// 但那要动 AI 流水线、要给存量活动兜底（老数据只有 `decisions` 这一份）、还要重跑 LLM。
/// ★那是功能改动，不是 prod 热修该冒的险★ —— 它排进 dev 线。
/// 这里做的是**当下就能止血**的一半：AI 的输出里本来就带着那两个小标题
/// （提示词里明写了「**关键决议**与**待办事项**」，实拍的输出也确实是这两个词），
/// 按它切一刀，两栏各拿各的。
///
/// ⚠★切不出来就整份都给★（fallback）：标题是 LLM 生成的，不保证每次都在。
///   ★切不准时宁可回到今天的样子（两栏都是全文），也不能切出个空的★ ——
///   一个空的「决议事项」比一个混着待办的「决议事项」糟得多：
///   前者看起来像 AI 什么都没产出，人会去重跑；后者至少内容都在。

/// 标题的写法有好几种可能：`**关键决议**` / `## 关键决议` / `关键决议：` / `一、关键决议`。
/// 只认「这一行里除了标记符号就剩这个词」，别去匹配正文里顺带提到的「待办事项」。
function 是标题行(行: string, 词们: string[]): boolean {
  // 去掉常见的 markdown / 中文列表标记与冒号，看剩下的是不是就是那个词。
  // ⚠★顺序有讲究:`**` 必须先去掉★——初版把去列表符号(`^[-*+]`)放在前面,
  //   于是 `**待办事项**` 的第一个 `*` 被当成列表符号吃掉,剩下 `*待办事项` 就再也匹配不上。
  //   (写完测试立刻就红了 —— 这正是先写测试的价值:错在我自己的解析器里。)
  // ⚠ 列表符号后面**要求有空白**:markdown 本来就这么规定,而不要求的话
  //   它会去啃粗体标记这类紧跟着字的星号。
  const 净 = 行.trim()
    .replace(/\*\*/g, '')
    .replace(/^#{1,6}\s*/, '')
    .replace(/^[-*+][ \t]+/, '')
    .replace(/^[一二三四五六七八九十]+[、.．]\s*/, '')
    .replace(/^\d+[、.．)]\s*/, '')
    .replace(/[:：]\s*$/, '')
    .trim()
  return 词们.some((w) => 净 === w)
}

const 决议词 = ['关键决议', '决议', '决议事项', '关键决策', '决策事项']
const 待办词 = ['待办事项', '待办', '行动项', '后续行动', 'TODO', 'Todo', '任务']

export type 拆分结果 = { 决议: string; 待办: string; 切开了: boolean }

export function 拆决议与待办(全文: string | null | undefined): 拆分结果 {
  const t = (全文 ?? '').trim()
  if (!t) return { 决议: '', 待办: '', 切开了: false }
  const 行 = t.split('\n')
  let 待办起 = -1
  let 决议起 = -1
  for (let i = 0; i < 行.length; i++) {
    if (决议起 < 0 && 是标题行(行[i], 决议词)) 决议起 = i
    // ★取**第一个**待办标题★：正文里可能再次出现这个词（比如「…形成待办事项」），
    //   但那时它不会独占一行，`是标题行` already 挡掉了。
    if (待办起 < 0 && 是标题行(行[i], 待办词)) 待办起 = i
  }
  // 没找到待办标题 → 切不动，整份都给（回到今天的样子）
  if (待办起 < 0) return { 决议: t, 待办: t, 切开了: false }
  // 待办标题在决议标题之前 → 顺序反了，不猜，整份都给
  if (决议起 >= 0 && 决议起 > 待办起) return { 决议: t, 待办: t, 切开了: false }

  const 决议段 = 行.slice(决议起 >= 0 ? 决议起 + 1 : 0, 待办起).join('\n').trim()
  const 待办段 = 行.slice(待办起 + 1).join('\n').trim()
  // ★任一半是空的就别切★：宁可两栏都是全文，也不要给出一个空栏（见头注）
  if (!决议段 || !待办段) return { 决议: t, 待办: t, 切开了: false }
  return { 决议: 决议段, 待办: 待办段, 切开了: true }
}
