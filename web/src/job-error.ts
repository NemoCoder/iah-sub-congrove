/// 把转写任务的失败原因翻成人话。★上游的原始 JSON 不许直接糊给用户★(2026-08-16 线上事故)。
///
/// 线上那次的 `job.error` 长这样:
///   `转写第 1 段: ASR 返回 502 Bad Gateway:{"error":{"code":null,"message":"ASR 上游连接失败:ConnectError","type":"upstream_error"}}`
/// 用户看到的是一整坨 JSON,而里面唯一对他有用的信息是「语音识别服务连不上,不是你的文件有问题」。
/// ★错误信息的读者是人,不是日志检索★ —— 原文该进日志(它已经在 media_jobs.error 里),
/// 界面上给一句能据以行动的话。
///
/// ══════ ★2026-08-17 prod 事故:这段翻译**指错了方向**★ ══════
///
/// liaoruili 报「语音服务出问题」。查 Loki,实情是**反的**:
///   · `ASR 响应自检 char_ts:3327` —— ★语音识别成功了,四次★;
///   · `生成 brief: LLM 返回 502 Bad Gateway` —— ★挂的是**后面**那一步(拿转写稿生成纪要)★。
///   · 根因是平台的 `vllm-qwen38-27b` 模型 pod 在 08:32Z 才起来,三次失败全在它之前。
///
/// 而上一版这里只有一条 `502|Bad Gateway → 「语音识别服务暂时连不上」`,
/// 于是 **LLM 的 502 冒充了 ASR 的 502**,把人指向一个根本没坏的服务。
///
/// ★教训:错误分类不能只看**是什么毛病**(502),还要看**哪一步出的毛病**。★
/// 同一个 502 落在不同阶段,对用户意味着完全不同的事 ——
/// 「转写没做成」和「转写做成了、只是没生成纪要」，后者已经有逐字稿可看。
///
/// ⚠ 判据取自后端 `media_ai.rs` 拼错误串时带的阶段前缀,它们本来就在:
///   ASR 侧 `转写第 N 段:` / `ASR 返回` / `请求 ASR 服务` / `解析 ASR 响应`
///   LLM 侧 `生成 brief|outline|decisions:` / `LLM 返回` / `请求 LLM 网关` / `压缩长转写`
///   其他   `ffmpeg 抽音轨` / `从对象存储取录屏` / `切分音频`
///   ★改后端那些 `.context("…")` 字面量时,这里要跟着改★——两处靠字符串对齐,
///   而对不齐时**不会报错**,只会又一次把人指向错误的方向。

/// 出错发生在哪一步。分出来是为了让「同一个 502」在不同阶段说不同的话。
export type 阶段 = 'asr' | 'llm' | '取文件' | '抽音轨' | '未知'

export function 判阶段(err: string): 阶段 {
  // ★先判 LLM★:LLM 那条链路的错误串里也可能出现「转写」二字
  //   (`压缩长转写: LLM 返回 …`)—— 顺序反了就会把 LLM 的错判成 ASR 的。
  if (/LLM 返回|生成 (brief|outline|decisions)|请求 LLM 网关|压缩长转写/.test(err)) return 'llm'
  if (/ASR 返回|转写第 \d+ 段|请求 ASR 服务|解析 ASR 响应|转写结果为空/.test(err)) return 'asr'
  if (/从对象存储取录屏/.test(err)) return '取文件'
  if (/ffmpeg|抽音轨|切分音频/i.test(err)) return '抽音轨'
  return '未知'
}

/// 是不是「上游连不上」这一类(用户做什么都没用,只能等)。
function 连不上(err: string): boolean {
  return /upstream_error|ConnectError|502|Bad Gateway|连接失败|503|Service Unavailable/.test(err)
}

export function 失败人话(err: string | null | undefined): string {
  const e = err || ''
  if (!e) return '未知原因'
  const 步 = 判阶段(e)

  // ── 上游连不上:同一个毛病,按阶段说不同的话 ──
  if (连不上(e)) {
    if (步 === 'llm') {
      // ★这句话的重点是「转写已经完成」★:它决定用户接下来做什么 ——
      //   逐字稿其实已经有了,他可以先去看逐字稿,不必干等。
      return '语音转写已完成，但生成纪要的 AI 模型暂时连不上（不是这个文件的问题）—— 逐字稿可以先看，服务恢复后点「转写」重试即可补上纪要'
    }
    if (步 === 'asr') {
      return '语音识别服务暂时连不上（不是这个文件的问题）—— 服务恢复后点「转写」重试即可'
    }
    // ★分不清哪一步时,别冒充任何一个具体服务★ —— 这正是上一版犯的错。
    return 'AI 服务暂时连不上（不是这个文件的问题）—— 服务恢复后点「转写」重试即可'
  }

  // ── 其余按具体毛病 ──
  if (/转写结果为空/.test(e)) return '没识别出人声（这段录制可能没有说话声，或音轨是静音的）'
  if (步 === '抽音轨') return '音轨提取失败（文件可能损坏，或是不支持的编码）'
  if (步 === '取文件') return '取不到这个录制文件（存储服务可能在抖）—— 稍后点「转写」重试'
  if (/超时|timeout/i.test(e)) {
    return 步 === 'llm'
      ? '语音转写已完成，但生成纪要超时（服务繁忙）—— 逐字稿可以先看，点「转写」可重试'
      : '转写超时（录制过长或服务繁忙）—— 可以再点一次「转写」'
  }
  // 认不出来的:截短,别把一整坨糊上去
  return e.length > 80 ? e.slice(0, 80) + '…' : e
}
