/// 排时间的唯一真相源 —— ★只要用例要「在日程页上看见这场活动」,就用这里的函数★。
///
/// 起因(2026-08-15):`ui.spec.ts` 的旁听用例只在**周六**红。判据链是这样的:
///   日程页默认显示**本周**,而周视图是**周日 → 周六**;
///   用例把活动排在「明天」—— 于是**周六那天**「明天」落进下一周,页面上根本不显示它,
///   报错却是 `element(s) not found`,★看起来像功能坏了★。
/// 修完那一处之后我没去搜同族 —— 结果 `acceptance-v05` 的 hover 用例当晚就以同样的方式红了。
/// ★同一个坑在 4 个 spec 里有 8 处★,所以不再逐处复制这段逻辑,抽到这里。
///
/// 三条约束缺一不可:
///   ① **在未来** —— 否则「即将进行」类的入口根本不列它;
///   ② **在当前显示的这一周内**(周日→周六);
///   ③ **钟点 ≥ 8** —— 日程页默认把**凌晨 0–8 点折叠**起来,排进去等于看不见,
///      而报错和「不存在」一模一样(这一条也是实测踩出来的:第一版修法排到 01:38,照样红)。
///
/// ⚠★否定断言更要用它★:像「拒绝之后日程里不再出现」这种,
///   如果活动本来就不在显示的那一周,**断言会凭空通过** —— 一个因为看错地方而通过的否定断言,
///   比红更坏:它把「没验到」记成了「验过了」。
export function 本周内可见的时刻(偏好钟点 = 15): Date {
  const d = new Date(); d.setHours(偏好钟点, 0, 0, 0)
  if (d.getTime() >= Date.now() + 30 * 60e3) return d          // 今天这个点还没到,直接用
  if (d.getDay() === 6) {                                       // ★周六:本周只剩今天★
    const h = Math.min(22, new Date().getHours() + 1)
    d.setHours(Math.max(8, h), 0, 0, 0)
    return d
  }
  d.setDate(d.getDate() + 1)                                    // 非周六:明天仍在本周(周日→周六)
  d.setHours(Math.max(8, 偏好钟点), 0, 0, 0)
  return d
}
